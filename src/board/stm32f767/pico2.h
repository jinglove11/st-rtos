/**
 * @file pico2.h
 * @brief Raspberry Pi Pico 2 (RP2350) 开发板定义
 */

#ifndef PICO2_H
#define PICO2_H

#include "rp2350.h"

/*============================================================================
 * LED 配置
 *============================================================================*/

#define PICO2_LED_PIN       25          // 板载 LED GPIO

/*============================================================================
 * UART 配置 (默认使用 UART0 连接 USB 串口)
 *============================================================================*/

#define PICO2_DEFAULT_UART      UART0
#define PICO2_UART_TX_PIN       0       // GPIO0 = UART0 TX
#define PICO2_UART_RX_PIN       1       // GPIO1 = UART0 RX
#define PICO2_UART_BAUDRATE     115200

/*============================================================================
 * 时钟配置
 *============================================================================*/

#define XOSC_HZ                (12 * 1000 * 1000)    // 外部晶振 12MHz
#define SYS_CLK_HZ             (150 * 1000 * 1000)   // 系统时钟 150MHz
#define PERI_CLK_HZ            SYS_CLK_HZ            // 外设时钟

/*============================================================================
 * 内存配置
 *============================================================================*/

#define SRAM_BASE              0x20000000
#define SRAM_SIZE              (520 * 1024)          // 520KB
#define FLASH_BASE             0x10000000
#define FLASH_SIZE             (16 * 1024 * 1024)   // 16MB (外部)

/*============================================================================
 * 栈配置
 *============================================================================*/

#define STACK_SIZE             0x2000               // 8KB 主栈

/*============================================================================
 * 延时函数 (简单忙等待)
 *============================================================================*/

static inline void delay_cycles(uint32_t cycles) {
    while (cycles--) {
        NOP();
    }
}

// 大约微秒级延时 (假设 150MHz)
static inline void delay_us(uint32_t us) {
    delay_cycles(us * 150);
}

// 大约毫秒级延时
static inline void delay_ms(uint32_t ms) {
    delay_us(ms * 1000);
}

#endif // PICO2_H
